import assert from 'node:assert/strict';
const base='http://127.0.0.1:8787';
async function call(path,method='GET',body,origin=base){const r=await fetch(base+'/api/'+path,{method,headers:body?{'Content-Type':'application/json',Origin:origin}:undefined,body:body?JSON.stringify(body):undefined});return {status:r.status,data:await r.json()};}
const before=(await call('state')).data;
assert.equal(before.items.length,0,'Run only against a fresh local database.');
const id=crypto.randomUUID();
const payload={id,name:'Leche',profile:'leticia',quantity:'2 litros',note:'descremada'};
assert.equal((await call('items','POST',payload,'https://untrusted.example')).status,403);
assert.equal((await call('items','POST',{...payload,profile:'unknown'})).status,400);
assert.equal((await call('items','POST',{...payload,name:' '})).status,400);
const results=await Promise.all([call('items','POST',payload),call('items','POST',{...payload,id:crypto.randomUUID(),name:' LECHÉ '})]);
assert.equal(results.filter(r=>r.status===201).length,1);
let state=(await call('state')).data;
assert.equal(state.items.length,1);
const item=state.items[0];
assert.equal(state.products.find(p=>p.name==='Leche').uses,1);
assert.equal((await call('items/'+item.id,'PATCH',{quantity:'3',note:'sin lactosa'})).status,200);
assert.equal((await call('items/'+item.id,'PATCH',{done:true})).status,200);
const next=crypto.randomUUID();
assert.equal((await call('items','POST',{...payload,id:next})).status,201);
assert.equal((await call('items/'+item.id,'PATCH',{done:false})).status,409);
assert.equal((await call('completed','DELETE',{})).status,200);
assert.equal((await call('items','POST',payload)).data.duplicate,true);
state=(await call('state')).data;
assert.equal(state.items.length,1);
assert.equal(state.products.find(p=>p.name==='Leche').uses,2);
assert.equal((await call('items/'+next,'DELETE',{})).status,200);
assert.equal((await call('state')).data.items.length,0);
console.log('PASS: origin/validation, concurrent add, normalization, idempotent retry after clearing, quantities, purchase/restore conflict, history and deletion.');
